/**
 * MotoLog Material 3 Theme.
 *
 * Supports three modes: Light, Dark, and AMOLED (pure black).
 * Defaults to system dark/light setting when [themeMode] is null.
 */
@Composable
fun MotoLogTheme(
    themeMode: ThemeMode? = null,
    content: @Composable () -> Unit
) {
    val isDarkSystem = isSystemInDarkTheme()

    val colorScheme = when (themeMode) {
        ThemeMode.LIGHT -> LightColorScheme
        ThemeMode.DARK -> DarkColorScheme
        ThemeMode.AMOLED -> AmoledColorScheme
        null -> if (isDarkSystem) DarkColorScheme else LightColorScheme
    }

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars =
                colorScheme == LightColorScheme
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = MotoLogTypography,
        content = content
    )
}
